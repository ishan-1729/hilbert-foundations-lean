#!/usr/bin/env python3
"""Generate docs/UNITS.md: one row per unit (statement of Hilbert), read from the
`## [id] Title` blocks in HilbertFoundations/**/*.lean.

For each unit it records the file, the section, the opening words of Hilbert's text, the
`**Status.**` line and the declarations that follow the block. `--check` exits non-zero if a unit
has a TODO status, if a labelled axiom or theorem of data/foundations.json has no unit, if a unit
id is duplicated, or if a unit marked "proved" is followed by declarations that use `sorry`.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECL = re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*'
                  r'(theorem|lemma|def|abbrev|structure|instance|inductive|class)\s+([^\s:(\[{]+)', re.M)


def where_key(loc: str):
    m = re.match(r'§\s*(\d+)', loc)
    if m:
        return (1, int(m.group(1)))
    return {'Introduction': (0, 0), 'Conclusion': (2, 0), 'Appendix': (3, 0)}.get(loc.split(',')[0].strip(), (4, 0))


def main() -> int:
    sys.stdout.reconfigure(encoding='utf-8')
    check = '--check' in sys.argv
    rows, problems = [], []
    for f in sorted((ROOT / 'HilbertFoundations').rglob('*.lean')):
        text = f.read_text(encoding='utf-8')
        blocks = list(re.finditer(r'/-!\s*\n## \[([\w.]+)\]\s*(.*?)\n(.*?)-/', text, re.S))
        for i, b in enumerate(blocks):
            uid, title, body = b.group(1), b.group(2).strip(), b.group(3)
            quote = ' '.join(l[1:].strip() for l in body.splitlines() if l.startswith('>'))
            words = re.sub(r'\s+', ' ', quote).split()
            first = ' '.join(words[:12]) + (' …' if len(words) > 12 else '')
            loc = re.search(r'^\*\(([^)]*)\)\*', body, re.M)
            m = re.search(r'\*\*Status\.\*\*\s*(.+)', body)
            status = m.group(1).strip() if m else 'MISSING'
            nxt = blocks[i + 1].start() if i + 1 < len(blocks) else len(text)
            tail = re.sub(r'/-.*?-/', '', text[b.end():nxt], flags=re.S)
            tail = re.sub(r'--[^\n]*', '', tail)
            decls = [d.group(2) for d in DECL.finditer(tail)]
            has_sorry = re.search(r'\bsorry\b', tail) is not None
            rel = f.relative_to(ROOT / 'HilbertFoundations').as_posix()
            rows.append(dict(uid=uid, title=title, file=rel, loc=loc.group(1) if loc else '', first=first,
                             status=status, decls=decls, sorry=has_sorry))
            if 'TODO' in status or status == 'MISSING':
                problems.append(f'{uid}: status not filled')
            if status.startswith('proved') and has_sorry:
                problems.append(f'{uid}: status says proved but a declaration uses sorry')
    data = json.loads((ROOT / 'data' / 'foundations.json').read_text(encoding='utf-8'))
    have = {r['uid'] for r in rows}
    for st in data['statements']:
        sys.path.insert(0, str(ROOT / 'scripts'))
        from make_skeletons import unit_id
        if unit_id(st) not in have:
            problems.append(f"{unit_id(st)}: labelled statement '{st['label']}' has no unit")
    seen = set()
    for r in rows:
        if r['uid'] in seen:
            problems.append(f"{r['uid']}: duplicate unit id")
        seen.add(r['uid'])
    rows.sort(key=lambda r: (where_key(r['loc']), r['file'], r['uid']))
    counts = {}
    for r in rows:
        key = r['status'].split(':')[0].strip().rstrip('.') or 'unknown'
        key = re.sub(r'\s+', ' ', key)
        counts[key] = counts.get(key, 0) + 1
    out = ["# Unit map: Hilbert, *The Foundations of Geometry* (1902)", '',
           'Generated by `scripts/unit_table.py` from the `## [id]` blocks in `HilbertFoundations/`.',
           'Do not edit by hand.', '', '| Status | Units |', '|---|---|']
    out += [f'| {k} | {v} |' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    out += ['', '| Unit | Where | Hilbert (opening words) | Status | Lean declarations |', '|---|---|---|---|---|']
    for r in rows:
        first = r['first'].replace('|', '\\|')
        decls = ', '.join(f'`{d}`' for d in r['decls']) or '—'
        flag = ' ⚠️ sorry' if r['sorry'] else ''
        out.append(f"| [`{r['uid']}`](../HilbertFoundations/{r['file']}) | {r['loc']} | {first} | {r['status']}{flag} | {decls} |")
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs' / 'UNITS.md').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(rows)} units; ' + ', '.join(f'{k}: {v}' for k, v in counts.items()))
    for p in problems:
        print('PROBLEM:', p)
    return 1 if (check and problems) else 0


if __name__ == '__main__':
    sys.exit(main())
